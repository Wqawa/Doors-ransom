// ============================================================================
//  lockdown.h
//
//  勒索阶段的「桌面清场」：把屏幕上所有能最小化的窗口收进任务栏，并且
//  在勒索期间不让它们回来。
//
//  为什么要这个：勒索窗口讲的是「你的电脑被我接管了」。如果用户随手
//  Alt+Tab 切回浏览器，整场戏就散了。所以进场时清空桌面，散场时把原本
//  最小化的那些窗口**放回原来的样子**。
//
//  ---- 三层做法，越靠后越硬 ----
//
//   1. 最小化：枚举所有顶层窗口，跳过本程序自己的、跳过程序自己声明
//      「不可最小化」的（任务栏、桌面、托盘、工具窗口），剩下的挨个
//      ShowWindow(SW_MINIMIZE)。窗口标题记下来写进日志，方便事后核对。
//
//   2. 拦截唤回：勒索期间吞掉 Win 键、Alt+Tab / Alt+Shift+Tab、Ctrl+Esc。
//      这一层只是减少闪烁，不是根本手段 —— 点任务栏按钮仍有可能把窗口
//      拉起来一下，因为那是发给 explorer 的普通鼠标消息，不在键盘钩子
//      能管的范围里（要管得装 WH_SHELL 钩子，代价大得多）。
//
//   3. 守望：定时器每隔一小会儿把**本次被我们收走的那些窗口**重新最小化。
//      这才是真正让「唤不回来」成立的一层：不管用户用什么办法把它弄回来
//      （任务栏、跳转列表、程序自己弹自己），下一拍就会被收回去。
//
//  为什么守望只盯「我们收走的那些」：如果谁被恢复到前台都无差别压下去，
//  就会变成「永远回不到任何窗口」，包括用户自己的新窗口，那是不可接受的。
//  只盯自己收走的那批，效果上同样叫不回来，但不会误伤。
//
//  ---- 边界 ----
//   * 只动**顶层、可见、有窗口标题、程序自己允许最小化**的窗口。
//   * 不碰本进程自己的窗口（脸、弹窗、特效层、覆盖层）。
//   * 不碰没有标题的窗口（消息窗口、隐藏的运行时窗口）。
//   * 只还原**自己收走的**那些窗口，且还原前核对进程号，句柄被系统回收
//     给了别的窗口也不会动它。
//   * 正常散场（付清 / 超时 / 退出 / --restore-windows）一定会还原。
//     被强杀（任务管理器）不会 —— 那种情况下窗口留在任务栏，点一下即回。
// ============================================================================
#pragma once

#ifndef WIN32_LEAN_AND_MEAN
#define WIN32_LEAN_AND_MEAN
#endif
#include <windows.h>

namespace lockdown {

// 清场：最小化所有能最小化的窗口，并开始阻止它们回来。
// 重复调用是安全的（会先把自己上一轮收走的窗口还原掉再重新收）。
// 返回这次收走的窗口数。
int Start();

// 散场：先停止拦截，再把收走的窗口放回原样。返回还原个数。
// 没在清场状态时是空操作。
int Restore();

// 是否正处于清场状态。
bool Active();

// 当前被收走的窗口数。
int LockedCount();

// 累计「被唤回来又被压回去」的次数。>0 说明第 2 层漏了、靠第 3 层兜住的，
// 排查时看这个数就知道输入拦截够不够。
int RepressedCount();

// 由宿主（director）的消息循环驱动。内部自己限流，不用每帧都调。
// 必须在**有窗口和消息循环的线程**上调用。
void Tick();

// 主机进程自己的窗口不要被清场，这里收集自己的窗口类名。
// 必须在 Start 之前调用，否则本程序的弹窗也会被收走。
void AddOwnClass(const wchar_t* className);

// 关掉拦键盘那一路（Win / Alt+Tab / Ctrl+Esc），只保留最小化 + 守望。
// 给「按了没反应」这类排查用。
void SetBlockKeys(bool on);
bool BlockKeys();

// 整个清场功能的开关（默认开）。--no-lockdown 走这里。
void SetEnabled(bool on);
bool Enabled();

// 给 overlay 的键盘钩子问的：这个 vk 现在该不该吞。
// 只有清场中且开关打开时才为 true。
bool ShouldSwallowKey(DWORD vkCode);

} // namespace lockdown
