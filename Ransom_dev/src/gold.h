//  gold.h
//
//  金币：把「凑够 500 Gold 赎回」这个机制搬到桌面上。
//
//  做法是在桌面上的**真实顶层文件夹**里生成 .lnk 快捷方式，文件名带金额后缀
//  （如 Gold_100.lnk）。快捷方式指向 Ransom_dev.exe --pay <金额> --token <编号>，
//  双击后新起的进程把金额通过跨进程消息发给正在运行的实体，然后自己退出。
//
//  安全边界（这一条最重要）：
//   * 只写 .lnk，**从不写可执行文件**（写 exe 是投放器特征，会被杀软拦）。
//   * 普通模式只写桌面的**顶层文件夹**，不递归；
//    硬核额外往各固定盘的**根目录**直接写（D:\ 这种），同样不往下递归。
//   * 跳过只读 / 隐藏 / 系统文件夹；盘根写不进去（多半是 C:\ 的权限）就跳过那个盘。
//   * **绝不覆盖已存在的文件**——同名就换名字，仍然冲突就跳过。
//   * 每一个生成的文件都登记在册，退出时只删除**登记过的**路径。
//     「只删自己造的东西」是硬规矩，你的 26 个原有快捷方式一个都不会碰。
//   * 同时写一份清单到 %LOCALAPPDATA%，万一本进程被强杀，
//     下次启动会自动按清单清理残留。
// ============================================================================
#pragma once

#ifndef WIN32_LEAN_AND_MEAN
#define WIN32_LEAN_AND_MEAN
#endif
#include <windows.h>

namespace gold {

// 原作就是 500
const int kGoal = 500;

bool Start(HINSTANCE hInst);

// 停服：删除本次生成的全部金币文件并移除清单。
void Stop();

// 在桌面顶层文件夹里生成金币 .lnk，直到总额 >= goal + 余量。
// 返回实际生成个数；一个都没生成返回 0。
int Spawn(int goal);

// 按 token 消费一枚金币（双击付款到达时调用）。
// 找到则删除该文件并返回金额；找不到返回 0。
//
// fakeMask 非空时回填这枚币的"污染掩码"：
//   0 = 真金币（正常付款）
//   1 = 前缀 "Gold" 被污染 -> 调用方应该扣计时器
//   2 = 面额数字被污染     -> 调用方应该把未付赎金加上面额
//   3 = 两个都污染         -> 两种惩罚同时生效
// 真假信息只存在内存里（生成时记的），文件本身只体现在名字上。
int Consume(int token, int* fakeMask = nullptr);

// 已生成金币的总额 / 当前还剩几个 / 累计生成过几个。
int SpawnedTotal();
int Alive();
int TotalCreated();

// 立刻删除全部剩余金币文件（付清或超时后调用）。
void Cleanup();

// 清理上一次运行遗留的残留（按清单）。启动时调用，返回清理个数。
int CleanupStale();

// 这个 .lnk 是不是本程序生成的金币？
// 判据很严：目标是本程序本体，且参数同时含 --pay 和 --token。
// 回收站模块靠它排除自己的金币，别人的快捷方式永远不会被误判。
bool IsOurCoinFile(const wchar_t* lnkPath);

} // namespace gold
